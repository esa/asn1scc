/* Checks of 009.asn1 / 009.acn (run by v4Tests/scripts/runWireTests.sh, legacy and --acn-v2, built with -DNDEBUG and
   ASan / UBSan, also at -wordSize 4; Issue 184): serially applied constraints with an extension marker.
   - Valid values encoded into a heap buffer of exactly REQUIRED_BYTES: bits and bytes = the X.691 model (extension bit,
     the root of the effective root, an addition as bit 1 + an unconstrained whole number; strings = pycrate), uPER and
     the default ACN encoding (the uPER body), REQUIRED_BITS pinned, decoded back from the written octets only.
     Rows marked (a) failed on master (C wrote past the buffer or did not compile, Ada did not compile or raised), rows
     marked (b) were self-consistent on master but not X.691 (master bytes in the comment), (c) are unchanged controls.
   - Rejected rows: decoded from exactly REQUIRED_BYTES, FALSE with the error code and the end bit position (C = Ada).
   - WBIG / W32: an extension addition of an unsigned typedef above the signed maximum cannot be written by the signed
     unconstrained whole number encoder: the encoder fails with the type's code at bit 0 (2^64 - 1 at ws 8, W32's
     2^32 - 1 at ws 4; at ws 8 W32 round-trips).
   Generated by the i184 implementer's gen009.py from a row table. CHECK, not assert: NDEBUG removes assert. The Ada
   twin 009_wire_test.adb checks the same values, bytes and rows. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "009.h"

static int failures = 0;

#define CHECK(c)                                                                          \
    do {                                                                                  \
        if (!(c)) {                                                                       \
            fprintf(stderr, "%s:%d: check failed: %s\n", __FILE__, __LINE__, #c);         \
            failures++;                                                                   \
        }                                                                                 \
    } while (0)

#define MAX1(n) ((n) > 0 ? (size_t)(n) : (size_t)1)

/* REQUIRED_BITS of an extensible INTEGER: the extension bit + an unconstrained whole number (73 at ws 8, 41 at ws 4) */
#define EXT_REQ ((int)(1 + 8 * (sizeof(asn1SccSint) + 1)))

/* encode v with ENC into exactly REQB octets (one octet for a type of 0 bits): nBits bits, the first (nBits + 7) / 8
   bytes of `expected`; decode from those octets only. A is & (empty for the string types, which are arrays) */
#define ROUND_TRIP(T, ENC, DEC, REQB, REQb, A, v, reqBits, expected, nBits)               \
    do {                                                                                  \
        byte* buf_ = calloc(MAX1(REQB), 1);                                               \
        static T dec_;                                                                    \
        BitStream s_;                                                                     \
        int e_ = 0;                                                                       \
        CHECK(buf_ != NULL);                                                              \
        CHECK((REQb) == (reqBits));                                                       \
        CHECK((nBits) <= (REQb));                                                         \
        CHECK(sizeof(expected) == MAX1(((nBits) + 7) / 8));                               \
        BitStream_Init(&s_, buf_, MAX1(REQB));                                            \
        CHECK(ENC(A(v), &s_, &e_, TRUE));                                                 \
        CHECK(e_ == 0);                                                                   \
        CHECK(s_.currentByte * 8 + s_.currentBit == (nBits));                             \
        CHECK(memcmp(buf_, (expected), ((nBits) + 7) / 8) == 0);                          \
        BitStream_AttachBuffer(&s_, buf_, ((nBits) + 7) / 8);                             \
        memset(&dec_, 0, sizeof dec_);                                                    \
        CHECK(DEC(A dec_, &s_, &e_));                                                     \
        CHECK(T##_Equal(A(v), A dec_));                                                   \
        CHECK(s_.currentByte * 8 + s_.currentBit == (nBits));                             \
        free(buf_);                                                                       \
    } while (0)

#define UPER(T, A, v, reqBits, expected, nBits)                                           \
    ROUND_TRIP(T, T##_Encode, T##_Decode, T##_REQUIRED_BYTES_FOR_ENCODING,                \
               T##_REQUIRED_BITS_FOR_ENCODING, A, v, reqBits, expected, nBits)
#define ACN(T, A, v, reqBits, expected, nBits)                                            \
    ROUND_TRIP(T, T##_ACN_Encode, T##_ACN_Decode, T##_REQUIRED_BYTES_FOR_ACN_ENCODING,    \
               T##_REQUIRED_BITS_FOR_ACN_ENCODING, A, v, reqBits, expected, nBits)

/* an INTEGER value: uPER and default-ACN round trips (the same bits) */
#define INT_UA(T, val, reqBits, nBits, ...)                                               \
    do {                                                                                  \
        static const byte x_[] = {__VA_ARGS__};                                           \
        T v_ = (val);                                                                     \
        UPER(T, &, v_, reqBits, x_, nBits);                                               \
        ACN(T, &, v_, reqBits, x_, nBits);                                                \
    } while (0)

/* decode the row (zero-padded) from exactly the type's REQUIRED_BYTES (uPER): FALSE, error code ERR, end bit
   position POS */
#define REJECT(T, ERR, POS, ...)                                                          \
    do {                                                                                  \
        static const byte src_[] = {__VA_ARGS__};                                         \
        static T v_;                                                                      \
        byte* buf_ = calloc(T##_REQUIRED_BYTES_FOR_ENCODING, 1);                          \
        BitStream s_;                                                                     \
        int e_ = 0;                                                                       \
        CHECK(buf_ != NULL);                                                              \
        CHECK(sizeof(src_) <= T##_REQUIRED_BYTES_FOR_ENCODING);                           \
        memcpy(buf_, src_, sizeof(src_));                                                 \
        BitStream_AttachBuffer(&s_, buf_, T##_REQUIRED_BYTES_FOR_ENCODING);               \
        memset(&v_, 0, sizeof v_);                                                        \
        CHECK(!T##_Decode(&v_, &s_, &e_));                                                \
        CHECK(e_ == (ERR));                                                               \
        CHECK(s_.currentByte * 8 + s_.currentBit == (POS));                               \
        free(buf_);                                                                       \
    } while (0)

/* encode v into exactly REQUIRED_BYTES with ENC: FALSE, error code ERR, end bit position POS */
#define ENC_FAIL(T, ENC, REQB, val, ERR, POS)                                             \
    do {                                                                                  \
        byte* buf_ = calloc(MAX1(REQB), 1);                                               \
        T v_ = (val);                                                                     \
        BitStream s_;                                                                     \
        int e_ = 0;                                                                       \
        CHECK(buf_ != NULL);                                                              \
        BitStream_Init(&s_, buf_, MAX1(REQB));                                            \
        CHECK(!ENC(&v_, &s_, &e_, TRUE));                                                 \
        CHECK(e_ == (ERR));                                                               \
        CHECK(s_.currentByte * 8 + s_.currentBit == (POS));                               \
        free(buf_);                                                                       \
    } while (0)

