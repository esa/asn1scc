    /* (a) IE21 10; master: root right, REQUIRED_BITS 8 < 17 for an addition (C overflow); Ada no compile */
    INT_UA(IE21, 10, EXT_REQ, 5, 0x50);
    /* (a) IE21 20 */
    INT_UA(IE21, 20, EXT_REQ, 17, 0x80, 0x8A, 0x00);
